const { app, BrowserWindow, WebContentsView, ipcMain } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { randomUUID } = require('node:crypto');
const assert = require('node:assert/strict');
const { ArenaBrowserService } = require('../electron/arena-browser-service');
const { createArenaWindow } = require('../electron/arena-window');
const directory = path.resolve(__dirname, '..', 'work', 'arena-popup-check', randomUUID());
fs.mkdirSync(path.join(directory, 'profile'), { recursive: true });
app.setPath('userData', path.join(directory, 'profile'));
app.setPath('sessionData', path.join(directory, 'profile'));
let popup, fixture, quitting = false;
app.whenReady().then(async () => {
  let submissions = 0, cockpitRequests = 0;
  fixture = http.createServer((request, response) => {
    if (request.method !== 'GET') submissions++;
    response.setHeader('Content-Type', 'text/html');
    response.end('<!doctype html><title>Local fixture</title><textarea id="payload"></textarea><form method="post"><button>Launch (manual)</button></form>');
  });
  await new Promise(resolve => fixture.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${fixture.address().port}`;
  const browser = new ArenaBrowserService({ WebContentsView, getWindow: () => popup.window, changed: tabs => popup?.update(tabs), allowedOrigins: [origin] });
  popup = createArenaWindow({ BrowserWindow, ipcMain, browser, isQuitting: () => quitting, openCockpit: () => { cockpitRequests++; } });
  await popup.create(); popup.show();
  assert.equal(BrowserWindow.getAllWindows().length, 1);
  assert.ok(popup.window.webContents.getURL().endsWith('/arena-window.html'));
  assert.equal(await popup.window.webContents.executeJavaScript('typeof window.mrgoose'), 'undefined');
  const a = await browser.create(origin, { label: 'A · <img src=x onerror=alert(1)>', attemptId: 'A' });
  assert.equal((await browser.page(a, 'fill', { selector: '#payload', value: 'Exact A 🪿' })).ok, true);
  const b = await browser.create(origin, { label: 'B · test', attemptId: 'B' });
  await browser.page(b, 'fill', { selector: '#payload', value: 'Exact B' });
  popup.show(a);
  const checkBounds = () => {
    const [width, height] = popup.window.getContentSize();
    assert.deepEqual(browser.entry(a).view.getBounds(), { x: 0, y: 52, width, height: height - 52 });
  };
  checkBounds();
  const resized = new Promise(resolve => popup.window.once('resize', resolve));
  popup.window.setContentSize(1000, 700); await resized; checkBounds();
  await popup.window.webContents.executeJavaScript(`window.arenaWindow.select(${JSON.stringify(b)})`);
  assert.equal(browser.activeTabId, b);
  const tabUi = await popup.window.webContents.executeJavaScript('({text:document.getElementById("tabs").textContent, images:document.getElementById("tabs").querySelectorAll("img").length})');
  assert.ok(tabUi.text.includes('A · <img')); assert.equal(tabUi.images, 0);
  assert.equal(await browser.entry(b).view.webContents.executeJavaScript('typeof window.arenaWindow'), 'undefined');
  await popup.window.webContents.executeJavaScript('window.arenaWindow.cockpit()'); assert.equal(cockpitRequests, 1);
  popup.hide(); assert.equal(popup.window.isVisible(), false);
  assert.equal((await browser.page(a, 'read', { selector: '#payload' })).text, 'Exact A 🪿');
  popup.window.close(); assert.equal(popup.window.isDestroyed(), false); assert.equal(browser.tabs.size, 2);
  popup.show(a); checkBounds(); assert.equal((await browser.page(b, 'read', { selector: '#payload' })).text, 'Exact B');
  assert.equal(submissions, 0);
  fs.writeFileSync(path.join(directory, 'popup.png'), (await popup.window.webContents.capturePage()).toPNG());
  console.log('PASS: standalone popup without Angular, two tabs, native bounds/resize, safe labels, IPC tab switch, optional cockpit, hide/read/reopen, no submit. Screenshot: ' + path.join(directory, 'popup.png'));
}).catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { quitting = true; fixture?.close(); app.exit(process.exitCode || 0); });
